int searchPropertyVariantType(const std::wstring& name) {
	const auto end = std::end(SEARCH_PROPERTY_TYPES);
	const auto found = std::lower_bound(std::begin(SEARCH_PROPERTY_TYPES), end, name,
		[](const SearchPropertyType& p, const std::wstring& n) { return std::wcscmp(p.name, n.c_str()) < 0; });
	return found != end && name == found->name ? found->variantType : 0;
}
